import { test, expect } from '../fixtures';

test.use({ serverScope: 'parity-S2' });
test('S2 The header summary reads "N of M showing", and it is the only status sentence on the page', async ({ page, server, api, tablets, guard, writes }, info) => {
  await guard(page);
  const fleet = await tablets(2);
  const [first, second] = fleet;
  if (!first || !second) throw new Error('Expected two joined tablets.');
  await expect.poll(async () => Object.keys((await api.config()).runtime.devices).length).toBe(2);
  await api.placeLogical({ columns: 2, rows: 1, deviceIds: fleet.map(tablet => tablet.id) });
  await api.scene({ type: 'calibration' });
  await page.goto(`${server.origin}/controller/app/`);
  const summary = page.locator(`header .status-${info.project.name === 'phone' ? 'compact' : 'full'}`);
  await expect(summary).toHaveText(info.project.name === 'phone' ? '2 of 2' : '2 of 2 showing');
  await expect(summary).toHaveClass(/chip-ok/);
  await expect(page.getByText(/showing the current image/i)).toHaveCount(0);
  await expect(page.locator('body').getByText(/^2 of 2 showing$/)).toHaveCount(1);
  const mutations = writes(page);
  await page.getByRole('tab', { name: 'Tests', exact: true }).click();
  await page.getByRole('button', { name: 'Black', exact: true }).click();
  await expect(summary).toHaveClass(/chip-ok/);
  const name = await page.locator(`#tablet-row-${second.id} .row-name`).textContent();
  await second.page.close();
  const problem = page.locator(`#tablet-row-${second.id}`);
  await expect(problem).toHaveAttribute('data-status', 'offline', { timeout: 2000 });
  await expect(summary).toHaveClass(/chip-warn/);
  await expect(summary).toHaveAccessibleDescription(`${name}: Offline.`);
  await summary.focus();
  await page.keyboard.press('Enter');
  await expect(problem).toBeFocused();
  await summary.focus();
  await page.keyboard.press('Space');
  await expect(problem).toBeFocused();
  await summary.click();
  await expect(problem).toBeFocused();
  await expect(page.getByRole('heading', { name: name ?? '', exact: true })).toHaveCount(0);
  expect(mutations).toEqual([]);
});
