import { DeviceIdSchema } from '../../src/api/devices';
import { ConfigSchema } from '../../src/api/config';
import { GridPreviewSchema } from '../../src/api/grid';
import { fleet as identities } from '../fixtures/fleet';
import { test, expect } from '../fixtures';

test.use({ serverScope: 'parity-A8' });
test('A8 Grid membership: an intentional exclusion and a manually entered size survive a tablet reconnect. A tablet that joins after an edit is offered through Include and is never added silently', async ({ server, api, tablets, page, writes, guard }) => {
  test.setTimeout(90_000);
  const fleet = await tablets(2, { viewport: { width: 400, height: 400 } });
  const [sized, excluded] = fleet;
  if (!sized || !excluded) throw new Error('Expected two tablets');
  await expect.poll(async () => Object.values((await api.config()).runtime.devices).filter(device => device.online).length).toBe(2);
  await api.placeLogical({ columns: 2, rows: 1, deviceIds: fleet.map(tablet => tablet.id) });
  await guard(page);
  const sent = writes(page);
  await page.goto(`${server.origin}/controller/app/`, { waitUntil: 'networkidle' });
  await page.getByRole('tab', { name: 'Layouts', exact: true }).click();
  await page.getByRole('button', { name: 'New grid…', exact: true }).click();
  const sheet = page.getByRole('dialog', { name: 'Build grid', exact: true });
  const sizedRow = sheet.locator(`[data-grid-device="${sized.id}"]`);
  const excludedRow = sheet.locator(`[data-grid-device="${excluded.id}"]`);
  await excludedRow.getByRole('button', { name: /^Exclude / }).click();
  await excludedRow.getByRole('switch', { name: /^Release / }).check();
  await sizedRow.locator('summary').click();
  await sizedRow.getByLabel(/^Width for /).fill('123');
  await sizedRow.getByLabel(/^Height for /).fill('45');
  await sizedRow.getByLabel(/^Width for /).focus();
  for (const tablet of fleet) {
    const deviceId = DeviceIdSchema.parse(tablet.id);
    const device = async () => ConfigSchema.parse(await api.config()).runtime.devices[deviceId];
    await tablet.page.close();
    await expect.poll(async () => (await device())?.online).toBe(false);
    const returned = await tablet.context.newPage();
    await guard(returned);
    await returned.goto(`${server.origin}/client/`);
    await expect.poll(async () => (await device())?.online).toBe(true);
  }
  await expect(sizedRow.getByLabel(/^Width for /)).toBeFocused();
  await expect(sizedRow.getByLabel(/^Width for /)).toHaveValue('123');
  await expect(sizedRow.getByLabel(/^Height for /)).toHaveValue('45');
  await expect(sizedRow.locator('summary')).toHaveText('123 × 45 logical units · operator');
  await expect(excludedRow.getByRole('button', { name: /^Include / })).toBeVisible();
  await expect(excludedRow.getByRole('switch', { name: /^Release / })).toBeChecked();
  const late = (await tablets(1, { ids: [identities[2]!.id], viewport: { width: 400, height: 400 } }))[0]!;
  const lateRow = sheet.locator(`[data-grid-device="${late.id}"]`);
  await expect(lateRow.getByRole('button', { name: /^Include / })).toBeVisible();
  await expect(sheet.locator('[data-grid-device] button[aria-label^="Exclude "]')).toHaveCount(1);
  await sheet.getByRole('button', { name: 'Keep inputs and close' }).click();
  await page.getByRole('tab', { name: 'Images', exact: true }).click();
  await page.getByRole('tab', { name: 'Layouts', exact: true }).click();
  await page.getByRole('button', { name: 'Edit grid…', exact: true }).click();
  await sizedRow.locator('summary').click();
  await expect(sizedRow.getByLabel(/^Width for /)).toHaveValue('123');
  await expect(excludedRow.getByRole('button', { name: /^Include / })).toBeVisible();
  await expect(lateRow.getByRole('button', { name: /^Include / })).toBeVisible();
  await lateRow.getByRole('button', { name: /^Include / }).click();
  await sheet.getByLabel('Columns', { exact: true }).fill('1');
  await sheet.getByLabel('Rows', { exact: true }).fill('2');
  const responsePromise = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v3/grid/preview');
  await sheet.getByRole('button', { name: 'Rebuild preview', exact: true }).click();
  const response = await responsePromise;
  expect(response.ok(), await response.text()).toBe(true);
  const preview = GridPreviewSchema.parse(await response.json());
  expect(preview.order).toEqual([sized.id, late.id]);
  const body = sent[0]!.postDataJSON();
  expect(body.logical_sizes[sized.id]).toEqual({ w: 123, h: 45 });
  expect(body.release_unselected).toEqual([excluded.id]);
  expect(sent.map(request => [request.method(), new URL(request.url()).pathname])).toEqual([['POST', '/api/v3/grid/preview']]);
  await expect(page.locator('[data-stage="preview"] [data-device-id]')).toHaveCount(2);
});
