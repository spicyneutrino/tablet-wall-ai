import { test, expect } from '../fixtures';
import { fileURLToPath } from 'node:url';
const image = fileURLToPath(new URL('../fixtures/images/two-colour.png', import.meta.url));

test.use({ serverScope: 'parity-C5' });
test('C5 Focus after Show stays on the trigger, or moves as `operator-content.js:536-558` does', async ({ server, api, tablets, page }) => {
  const [tablet] = await tablets(1);
  if (!tablet) throw new Error('Expected tablet');
  await api.placeLogical({ columns: 1, rows: 1, deviceIds: [tablet.id] });
  await api.upload(image);
  await page.goto(`${server.origin}/controller/app/`, { waitUntil: 'networkidle' });
  const pick = page.getByRole('button', { name: 'two-colour.png', exact: true });
  const show = page.getByRole('button', { name: 'Show on wall', exact: true });
  await pick.click();
  await show.focus();
  await show.press('Enter');
  await expect(page.getByRole('button', { name: 'All images' })).toBeFocused();
  await pick.click();
  await page.route('**/api/v3/scene', route => route.fulfill({ status: 422, contentType: 'application/json', body: JSON.stringify({ detail: 'Image rejected. Choose another image.' }) }), { times: 1 });
  await show.focus();
  await show.press('Enter');
  await expect(page.getByRole('status').filter({ hasText: 'Image rejected' })).toBeVisible();
  await expect(show).toBeFocused();
  let release: (() => void) | undefined;
  const held = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/v3/scene', async route => { await held; await route.continue(); }, { times: 1 });
  await show.press('Enter');
  await expect(page.getByRole('button', { name: 'Showing…', exact: true })).toHaveAttribute('aria-busy', 'true');
  const all = page.getByRole('button', { name: 'All images' });
  await all.focus();
  release?.();
  await expect(page.getByRole('status').filter({ hasText: 'Content applied.' })).toBeVisible();
  await expect(all).toBeFocused();
  await pick.click();
  await page.locator('[data-stage="preview"] [data-device-id]').click();
  await show.focus();
  await show.press('Enter');
  await expect(all).toBeFocused();
});
