import { test, expect } from '../fixtures';
import { DeviceIdSchema } from '../../src/api/devices';
import { ConfigSchema } from '../../src/api/config';
import { DisplayResponseSchema } from '../../src/api/measure';

test.use({ serverScope: 'parity-M2' });
test('M2 The ruler check writes nothing. Its review is invalidated when the viewport or inputs change, and a stale review cannot be saved', async ({ server, api, tablets, page, writes, guard, axe }) => {
  test.setTimeout(90_000);
  await guard(page);
  const [tablet, other] = await tablets(2);
  if (!tablet || !other) throw new Error('Two real tablets are required.');
  const id = DeviceIdSchema.parse(tablet.id);
  await expect.poll(async () => (await api.config()).runtime.devices[id]?.online).toBe(true);
  const initial = ConfigSchema.parse(await api.config());
  const response = await api.request.put(`/api/v3/displays/${id}`, { headers: { 'If-Match': initial.etag }, data: {
    active_width_mm: 200, active_height_mm: 112.5, bezels: { left: 0, right: 0, top: 0, bottom: 0 },
    panel_pixels: null, label: 'Measured tablet', provenance: 'manual',
  } });
  expect(response.ok(), await response.text()).toBe(true);
  DisplayResponseSchema.parse(await response.json());
  await api.placeLogical({ columns: 2, rows: 1, deviceIds: [id, other.id] });
  const before = ConfigSchema.parse(await api.config());
  const recorded = writes(page);
  await page.goto(`${server.origin}/controller/app/`, { waitUntil: 'networkidle' });
  await page.locator(`#tablet-row-${id}`).click();
  await page.getByRole('button', { name: 'Measure…', exact: true }).click();
  await page.getByLabel('Which model is it?').selectOption('manual');
  await page.getByRole('button', { name: 'Next: size and bezels', exact: true }).click();
  await page.getByRole('button', { name: 'Next: ruler check', exact: true }).click();
  await expect(page.getByText(/Set the server’s tablet origin/)).toBeVisible();
  await tablet.page.goto(`${server.origin}/client/?calibrate=1`);
  await expect(tablet.page.getByRole('heading', { name: 'Measure this tablet' })).toBeVisible();
  expect(await tablet.page.evaluate(() => localStorage.getItem('tablet-wall-device-id'))).toBe(id);
  await tablet.page.locator('#ruler-span').selectOption('short');
  await expect(tablet.page.locator('#ruler-horizontal-label')).toHaveText('Horizontal: 0 to 200 CSS px');
  await expect(tablet.page.locator('#ruler-vertical-label')).toHaveText('Vertical: 0 to 50 CSS px');
  await tablet.page.screenshot({ path: '/tmp/u26-shots/3170a157/tablet-ruler.png' });
  await expect.poll(async () => ConfigSchema.parse(await api.config()).runtime.devices[id]?.online).toBe(true);
  await page.getByLabel('Line A', { exact: true }).fill('50');
  await page.getByLabel('Line B', { exact: true }).fill('12.5');
  await page.getByText(/^Line lengths on screen \(/).click();
  await page.getByLabel('Line B span', { exact: true }).fill('50');
  await page.getByText(/^Line lengths on screen \(/).click();
  await page.getByRole('button', { name: 'Check result', exact: true }).click();
  await expect(page.getByText(/^Ruler gives \d+\.\d × \d+\.\d mm$/)).toBeVisible();
  await page.getByLabel('Use the ruler values', { exact: true }).check();
  await page.screenshot({ path: `/tmp/u26-shots/3170a157/ruler-checked-${page.viewportSize()?.width}.png`, fullPage: true });
  if (page.viewportSize()?.width === 1440) {
    const dimensions = await page.locator('.sidebar-scroll').evaluate(el => ({ height: el.clientHeight, scroll: el.scrollHeight,
      children: [...el.querySelectorAll('.measure-stepper, .measure-controls, .measure-footer')].map(child => ({ class: child.className, height: child.getBoundingClientRect().height, top: child.getBoundingClientRect().top, bottom: child.getBoundingClientRect().bottom })) }));
    expect(dimensions.scroll, JSON.stringify(dimensions)).toBeLessThanOrEqual(dimensions.height);
  }
  expect((await axe(page)).violations).toEqual([]);
  expect(recorded).toHaveLength(2);
  expect(recorded.every(request => request.method() === 'POST' && new URL(request.url()).pathname === '/api/v3/calibration-check')).toBe(true);
  for (const request of recorded) expect(request.headers()['if-match']).toBeTruthy();
  const after = ConfigSchema.parse(await api.config());
  expect(after.etag).toBe(before.etag);
  expect(after.displays).toEqual(before.displays);
  expect(after.calibrations).toEqual(before.calibrations);
  await page.getByLabel('Line A', { exact: true }).fill('51');
  await expect(page.getByText(/tablet, viewport or inputs changed/)).toBeVisible();
  await page.getByRole('button', { name: 'Next: review', exact: true }).click();
  await expect(page.locator('.measure-error')).toContainText('Check the current ruler measurements');
  expect(recorded).toHaveLength(2);
  await page.getByRole('button', { name: 'Check result', exact: true }).click();
  await page.getByLabel('Keep the model values', { exact: true }).check();
  await page.getByRole('button', { name: 'Next: review', exact: true }).click();
  await tablet.page.setViewportSize({ width: 810, height: 450 });
  await expect.poll(async () => ConfigSchema.parse(await api.config()).runtime.devices[id]?.viewport?.width).toBe(810);
  await page.getByRole('button', { name: 'Save measurements', exact: true }).click();
  await expect(page.locator('.measure-error')).toContainText('ruler review is stale');
  expect(recorded).toHaveLength(4);
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByRole('button', { name: 'Check result', exact: true }).click();
  await page.getByLabel('Use the ruler values', { exact: true }).check();
  await page.getByRole('button', { name: 'Next: review', exact: true }).click();
  await page.getByText('Advanced: quarter turn, anchor, offsets', { exact: true }).click();
  await page.getByLabel('Panel offset X', { exact: true }).fill('1');
  await page.getByRole('button', { name: 'Save measurements', exact: true }).click();
  await expect(page.locator('.measure-error')).toContainText('ruler review is stale');
  expect(recorded).toHaveLength(6);
  await page.locator('[data-stage="preview"]').focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('heading', { name: `Measure Tablet ${before.runtime.devices[DeviceIdSchema.parse(other.id)]?.number}`, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Next: size and bezels', exact: true }).click();
  await expect(page.getByLabel('Which model is it?')).toHaveAttribute('aria-invalid', 'true');
  expect(recorded).toHaveLength(6);
  await page.locator('[data-stage="preview"]').focus();
  await page.keyboard.press('ArrowRight');
  await page.getByRole('button', { name: 'Next: size and bezels', exact: true }).click();
  await page.getByRole('button', { name: 'Next: ruler check', exact: true }).click();
  await page.getByRole('button', { name: 'Check result', exact: true }).click();
  await page.getByLabel('Use the ruler values', { exact: true }).check();
  await page.getByRole('button', { name: 'Next: review', exact: true }).click();
  await page.getByRole('button', { name: 'Save measurements', exact: true }).click();
  await expect(page.getByRole('heading', { name: /^Measure Tablet/ })).toHaveCount(0);
  const measured = ConfigSchema.parse(await api.config()).calibrations.find(calibration => calibration.device_id === id);
  expect(measured?.method).toBe('ruler-measured');
  expect(measured?.viewport_width).toBe(810);
  expect(measured?.mm_per_css).toEqual([0.255, 0.25]);
  expect(measured?.panel_offset_mm).toEqual([1, 0]);
  console.log('M2: ruler checks write no revisions; same-tablet ruler; input, viewport, advanced and device invalidation; a fresh review saves the checked scales and viewport.');
});
