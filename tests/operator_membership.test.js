"use strict";
const assert = require("node:assert/strict");
const { membership } = require("../frontend/controller/operator-grid.js");
const setup = membership();
const layout = { kind: "logical", placements: {} };
setup.observe({ first: { number: 1, online: false } }, layout);
setup.observe({ first: { number: 1, online: true, viewport: { width: 900, height: 1280 } } }, layout);
assert.equal(setup.view().first.included, true, "#24 registration before online must become selected without reload");
assert.deepEqual(setup.view().first.size, { w: 70, h: 100 }, "fresh viewport replaces the untouched square fallback");
setup.include("first", false);
setup.observe({ first: { number: 1, online: false }, second: { number: 2, online: true, viewport: { width: 600, height: 1000 } } }, layout);
setup.observe({ first: { number: 1, online: true }, second: { number: 2, online: true } }, layout);
assert.equal(setup.view().first.included, false, "intentional exclusion survives reconnect");
assert.equal(setup.view().second.included, false, "joins after membership edit require explicit Include");
setup.include("second", true);
setup.size("second", { w: 77, h: 90 });
setup.observe({ second: { online: true, viewport: { width: 1000, height: 500 } } }, layout);
assert.deepEqual(setup.view().second.size, { w: 77, h: 90 });
const reviewed = membership();
reviewed.observe({ a: { online: true } }, layout);
reviewed.freeze();
reviewed.observe({ a: { online: true, viewport: { width: 500, height: 1000 } }, b: { online: true } }, layout);
assert.deepEqual(reviewed.view().a.size, { w: 100, h: 100 }, "reviewed inputs never resize under telemetry");
assert.equal(reviewed.view().b.included, false);
console.log("Late join, viewport provenance, exclusions and reviewed membership passed");
