"use strict";
const assert = require("node:assert/strict");
const { fitLogical, arrangeLogical, rotateLogical } = require("../frontend/controller/operator-state.js");
const a = { x: -20, y: 10, w: 100, h: 70, bezel: { top: 3, right: 5, bottom: 7, left: 11 } };
const b = { x: 150, y: -10, w: 80, h: 120, bezel: { top: 0, right: 0, bottom: 0, left: 0 } };
const layout = { kind: "logical", width: 1000, height: 700, sizing: { mode: "tablets", padding: 4 }, placements: { a: structuredClone(a), b: structuredClone(b) } };
fitLogical(layout);
assert.equal(layout.width, 258); assert.equal(layout.height, 128);
assert.equal(layout.placements.a.x, 4); assert.equal(layout.placements.b.y, 4);
assert.equal(layout.placements.b.x - layout.placements.a.x, b.x - a.x, "fit preserves relative positions");
assert.deepEqual(layout.placements.a.bezel, a.bezel);
const source = structuredClone(layout);
const packed = arrangeLogical(layout, ["b", "a"], { columns: 2, gap: 6 });
assert.equal(packed.placements.a.x - packed.placements.b.x, b.w + 6);
assert.deepEqual(layout, source, "packing is a local proposal without mutating its input");
const fixed = { ...layout, width: 1000, height: 700, sizing: { mode: "fixed", padding: 0 } };
const tiled = arrangeLogical(fixed, ["a", "b"], { columns: 2, gap: 10, tile: true, preserveAspect: true });
assert.equal(tiled.width, 1000); assert.equal(tiled.height, 700);
assert.ok(tiled.placements.a.x + tiled.placements.a.w <= tiled.placements.b.x);
assert.deepEqual(tiled.placements.a.bezel, a.bezel);
assert.ok(tiled.placements.a.h < 700, "keep-aspect tiling leaves room instead of stretching the screen");
const sparse = arrangeLogical(fixed, ["a"], { columns: 2, rows: 2, gap: 10, tile: true, preserveAspect: false });
assert.equal(sparse.placements.a.h, 345, "explicit rows reserve empty trailing cells");
assert.deepEqual(sparse.placements.b, fixed.placements.b, "a scoped tile preserves unselected placements");
const screen = arrangeLogical(fixed, ["b"], { columns: 1, rows: 1, gap: 0, tile: true, aspects: { b: 2 } });
assert.equal(screen.placements.b.w / screen.placements.b.h, 2, "known screen aspect is retained instead of a stretched draft shape");
assert.throws(() => arrangeLogical(fixed, ["a", "b"], { columns: 1, rows: 1, gap: 0, tile: true }), /do not fit/);
const rotated = rotateLogical(a);
assert.equal(rotated.w, a.h); assert.equal(rotated.h, a.w);
assert.deepEqual(rotated.bezel, { top: 11, right: 3, bottom: 5, left: 7 });
assert.throws(() => arrangeLogical(fixed, ["a"], { columns: 0, gap: 0 }), /whole/);
assert.throws(() => arrangeLogical(fixed, ["missing"], { columns: 1, gap: 0 }), /order changed/);
console.log("Relative fit, packing, fixed tiling and asymmetric bezel rotation passed");
